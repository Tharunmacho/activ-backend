// Isolated loopback Mongo; fake Firebase adapter. No production DB/provider calls.
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const path = require('node:path');
const { MongoMemoryServer } = require('mongodb-memory-server-core');
Object.assign(process.env, { NODE_ENV: 'test', PUSH_ENABLED: 'false', JWT_SECRET: 'visitor-test-only' });
let mongo;
(async () => {
    mongo = await MongoMemoryServer.create({ binary: { downloadDir: path.resolve(__dirname, '../node_modules/.cache/mongodb-memory-server') }, instance: { ip: '127.0.0.1' } });
    assert.match(mongo.getUri(), /^mongodb:\/\/127\.0\.0\.1:/);
    process.env.MONGODB_URI = mongo.getUri();
    await mongoose.connect(mongo.getUri(), { autoIndex: false });
    const { VisitorDevice, PublicNotice, VisitorDelivery } = require('../src/modules/notifications/visitorPush.models');
    const MemberDevice = require('../src/modules/notifications/pushDevice.model');
    const Announcement = require('../src/modules/announcements/announcement.model');
    const Event = require('../src/modules/events/event.model');
    const service = require('../src/modules/notifications/visitorPush.service');
    const updates = require('../src/modules/announcements/announcement.service');
    const push = require('../src/modules/notifications/push.service');
    await Promise.all([VisitorDevice, PublicNotice, VisitorDelivery, MemberDevice, Announcement, Event].map(model => model.createIndexes()));
    const fixture = await service.install();
    assert.equal(fixture.key.length, 64);
    const raw = await VisitorDevice.findById(fixture.id).select('+secretHash').lean();
    assert.notEqual(raw.secretHash, fixture.key, 'installation bearer stored only as hash');
    const token = 'local-visitor-token-123456789';
    await service.register(fixture.key, { token, platform: 'android' });
    await assert.rejects(service.register('invalid', { token, platform: 'android' }), error => error.statusCode === 401);
    const another = await service.install();
    await assert.rejects(service.register(another.key, { token, platform: 'ios' }), error => error.statusCode === 409, 'another installation cannot claim a token');
    await VisitorDevice.updateOne({ _id: another.id }, { $set: { lastSeenAt: new Date(Date.now() - 91 * 86400000) } });
    await assert.rejects(service.register(another.key, { token: 'other-test-token-12345678', platform: 'ios' }), error => error.statusCode === 401, 'expiry enforced before TTL cleanup');
    let sequence = 0;
    const createPublic = async () => {
        const item = await updates.create({ title: `Dear {Name}, update ${++sequence}`, body: '<p>Welcome <strong>{name}</strong></p>', status: 'published', audience: 'all', includeVisitors: true, targets: [], deliveryChannels: { email: false, whatsapp: false, push: true } });
        return PublicNotice.findOne({ sourceId: item.id }).lean();
    };
    const notice = await createPublic();
    await updates.create({ title: 'Private member update', body: 'Private', audience: 'all', status: 'published' });
    await updates.create({ title: 'Paid update', body: 'Paid', audience: 'paid', status: 'published' });
    const event = await Event.create({ title: 'Public event', slug: 'public-local-visitor', status: 'published', channel: 'public', audience: 'all', reachEveryone: true,
        mode: 'online', startAt: new Date(Date.now() + 86400000), endAt: new Date(Date.now() + 90000000), onlineUrl: 'https://meet.example.test/secret', description: 'Public event description' });
    const feed = await service.feed();
    assert.equal(feed.length, 2);
    assert(feed.some(row => row.title.startsWith('Dear ACTIVian')));
    assert.equal(feed.find(row => row.kind === 'announcement').body, 'Welcome ACTIVian', 'public projection personalizes and strips authored HTML before display');
    assert(!JSON.stringify(feed).includes('secret') && !JSON.stringify(feed).includes('onlineUrl'), 'public projection withholds joining credentials');
    assert.equal(service.publicEligible('event', { ...event.toObject(), channel: 'members', reachEveryone: false, showOnOnboarding: false }), false);
    assert.equal(service.publicEligible('event', { ...event.toObject(), audience: 'paid', showOnOnboarding: true }), false);
    assert.equal(service.publicEligible('event', { ...event.toObject(), channel: 'members', targets: [{ state: 'Tamil Nadu' }], showOnOnboarding: true }), true, 'explicit onboarding option preserves existing public event logic');
    assert.equal(service.publicEligible('announcement', { status: 'published', audience: 'all', includeVisitors: true, state: 'Tamil Nadu' }), false);
    const sent = [];
    const client = { send: async payload => { sent.push(payload); return 'fake-provider-id'; } };
    await Promise.all([service.processBatch(client), service.processBatch(client)]);
    assert.equal(sent.length, 2, 'concurrent workers deliver each publication once');
    await service.processBatch(client);
    assert.equal(sent.length, 2, 'completed jobs do not replay');
    assert(sent.every(payload => payload.token === token && payload.data.visitorId === fixture.id && !payload.data.userId));
    assert(sent.every(payload => payload.android.notification.channelId === 'activ_updates' && payload.android.notification.priority === 'high'), 'visitor notification display matches account heads-up priority');
    assert.equal((await service.opened(fixture.key, notice._id, 'push')).recorded, true);
    assert.equal((await service.opened(fixture.key, notice._id, 'push')).recorded, false, 'open is idempotent');
    const notTargeted = await service.install();
    assert.equal((await service.opened(notTargeted.key, notice._id, 'push')).recorded, false, 'other installation cannot forge an attributed open');
    const retry = await createPublic();
    await service.processBatch({ send: async () => { const error = new Error('offline'); error.code = 'messaging/server-unavailable'; throw error; } });
    let delivery = await VisitorDelivery.findOne({ notice: retry._id, device: fixture.id }).lean();
    assert.equal(delivery.status, 'pending'); assert(!delivery.sentAt);
    await VisitorDelivery.updateOne({ _id: delivery._id }, { $set: { nextAttemptAt: new Date(0) } });
    await service.processBatch(client);
    assert.equal((await VisitorDelivery.findById(delivery._id)).status, 'sent', 'retry after transient failure');
    const withdrawn = await createPublic(); await service.fanout();
    await Announcement.updateOne({ _id: withdrawn.sourceId }, { $set: { includeVisitors: false } });
    const beforeWithdrawal = sent.length;
    await service.processBatch(client);
    assert.equal(sent.length, beforeWithdrawal);
    assert.equal((await VisitorDelivery.findOne({ notice: withdrawn._id })).lastError, push.skipReasons.sourceUnavailable);
    await assert.rejects(service.feed(withdrawn._id), error => error.statusCode === 404);
    const revoked = await createPublic(); await service.fanout();
    await service.unregister(fixture.key);
    await service.processBatch(client);
    assert.equal((await VisitorDelivery.findOne({ notice: revoked._id })).status, 'skipped', 'opt-out applies to queued messages');
    assert.equal((await VisitorDelivery.findOne({ notice: revoked._id })).lastError, push.skipReasons.visitorDisabled);
    await service.register(fixture.key, { token, platform: 'android' });
    const login = await createPublic(); await service.fanout();
    await push.register(new mongoose.Types.ObjectId(), { token, platform: 'android' });
    await service.processBatch(client);
    assert.equal((await VisitorDelivery.findOne({ notice: login._id })).status, 'skipped', 'login detaches visitor ownership');
    assert.equal((await VisitorDevice.findById(fixture.id)).enabled, false);
    await assert.rejects(service.register(fixture.key, { token, platform: 'android' }), error => error.statusCode === 409);
    await MemberDevice.deleteMany({ token });
    await service.register(fixture.key, { token, platform: 'android' });
    const invalid = await createPublic();
    await service.processBatch({ send: async () => { const error = new Error('gone'); error.code = 'messaging/registration-token-not-registered'; throw error; } });
    assert.equal((await VisitorDevice.findById(fixture.id)).enabled, false);
    assert.equal((await VisitorDelivery.findOne({ notice: invalid._id })).status, 'failed');
    // A delayed response for the old token must not revoke a refreshed registration.
    await service.register(fixture.key, { token, platform: 'android' });
    const refreshedToken = 'local-refreshed-visitor-token-123456789';
    const rotating = await createPublic();
    await service.processBatch({ send: async payload => {
        assert.equal(payload.token, token);
        await service.register(fixture.key, { token: refreshedToken, platform: 'android' });
        const error = new Error('old token expired during refresh');
        error.code = 'messaging/registration-token-not-registered'; throw error;
    } });
    const refreshed = await VisitorDevice.findById(fixture.id).select('+token').lean();
    assert.equal(refreshed.enabled, true, 'an old-token failure preserves the refreshed registration');
    assert.equal(refreshed.token, refreshedToken);
    assert.equal((await VisitorDelivery.findOne({ notice: rotating._id })).status, 'failed');
    const afterRefresh = await createPublic();
    const refreshedPayloads = [];
    await service.processBatch({ send: async payload => { refreshedPayloads.push(payload); return 'fake-refreshed-id'; } });
    assert(refreshedPayloads.some(payload => payload.token === refreshedToken && payload.data.publicNotificationId === String(afterRefresh._id)), 'subsequent publications reach the refreshed token');
    await service.unregister(fixture.key);
    // Revision replaces the old public record; previously targeted IDs cannot leak it.
    const revision = await updates.update(notice.sourceId, { title: 'Revised public notice' });
    const revisedFeed = await service.feed();
    assert.equal(revisedFeed.filter(item => item.sourceId === revision.id).length, 1);
    await assert.rejects(service.feed(notice._id), error => error.statusCode === 404);
    const browser = await service.install();
    await service.register(browser.key, { token: 'browser-visitor-token-123456789', platform: 'web' });
    const browserNotice = await createPublic();
    const browserSent = [];
    for (let i = 0; i < 3; i++) await service.processBatch({ send: async payload => { browserSent.push(payload); return 'fake-browser-id'; } });
    const browserPayload = browserSent.find(payload => payload.data.publicNotificationId === String(browserNotice._id));
    assert(browserPayload, 'opted-in website visitor receives a public publication');
    assert.equal(browserPayload.notification, undefined, 'web worker must validate installation before display');
    assert.equal(browserPayload.webpush.headers.TTL, '86400');
    assert.deepEqual(browserPayload.data, { audience: 'visitor', visitorId: browser.id, publicNotificationId: String(browserNotice._id) });
    const disabledChannel = await createPublic();
    await service.fanout();
    await Announcement.updateOne({ _id: disabledChannel.sourceId }, { $set: { 'deliveryChannels.push': false } });
    const expired = await createPublic();
    await service.fanout();
    await PublicNotice.collection.updateOne({ _id: expired._id }, { $set: { createdAt: new Date(Date.now() - 2 * 86400000) } });
    let unexpectedSends = 0;
    const noSend = { send: async () => { unexpectedSends++; throw new Error('Unexpected provider call'); } };
    await service.processBatch(noSend);
    const channelDelivery = await VisitorDelivery.findOne({ notice: disabledChannel._id, device: browser.id }).lean();
    const expiredDelivery = await VisitorDelivery.findOne({ notice: expired._id, device: browser.id }).lean();
    assert.equal(channelDelivery.status, 'skipped');
    assert.equal(channelDelivery.lastError, push.skipReasons.channelOff);
    assert.equal(expiredDelivery.status, 'skipped');
    assert.equal(expiredDelivery.lastError, push.skipReasons.expired);
    assert.equal(unexpectedSends, 0, 'expired or channel-disabled notices never call Firebase');
    // Only new outcomes get reasons; a historical blank skipped record stays
    // untouched even when the worker runs again.
    await VisitorDelivery.updateOne({ _id: channelDelivery._id }, { $set: { lastError: '' } });
    await service.processBatch(noSend);
    assert.equal((await VisitorDelivery.findById(channelDelivery._id)).lastError, '');
    assert.equal(unexpectedSends, 0);
    console.log('PASS visitor public projection, membership gates, credential expiry, ownership, dedup, receipt isolation, retry, revocation and login transitions');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await mongoose.disconnect(); if (mongo) await mongo.stop(); });
