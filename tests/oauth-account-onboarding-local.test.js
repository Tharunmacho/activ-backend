// Real loopback Mongo/HTTP; provider and email transports are fixtures only.
const assert = require('node:assert/strict');
const path = require('node:path');
const mongoose = require('mongoose');
const { MongoMemoryServer } = require('mongodb-memory-server-core');
Object.assign(process.env, { NODE_ENV: 'test', JWT_SECRET: 'local-oauth-onboarding-secret', JWT_REFRESH_SECRET: 'local-oauth-refresh-secret',
    GOOGLE_CLIENT_ID: 'fixture-google', GOOGLE_CLIENT_SECRET: 'fixture-secret', FACEBOOK_APP_ID: 'fixture-facebook', FACEBOOK_APP_SECRET: 'fixture-secret',
    LINKEDIN_CLIENT_ID: 'fixture-linkedin', LINKEDIN_CLIENT_SECRET: 'fixture-secret', FRONTEND_URL: 'http://localhost:8080' });
let mongo;
(async () => {
    mongo = await MongoMemoryServer.create({ binary: { downloadDir: path.resolve(__dirname, '../node_modules/.cache/mongodb-memory-server') }, instance: { ip: '127.0.0.1' } });
    assert.match(mongo.getUri(), /^mongodb:\/\/127\.0\.0\.1:/);
    process.env.MONGODB_URI = mongo.getUri(); await mongoose.connect(mongo.getUri());
    const Auth = require('../src/modules/auth/auth.model');
    const Member = require('../src/modules/members/memberdetails.model');
    const Flow = require('../src/modules/auth/oauthFlow.model');
    const Identity = require('../src/modules/auth/oauthIdentity.model');
    const Application = require('../src/modules/applications/application.model');
    await Promise.all([Auth.init(), Member.init(), Flow.init(), Identity.init()]);
    require('../src/modules/admin/admin.repository').findRawByEmail = async email => email === 'admin@gmail.com' ? { role: 'super_admin' } : null;
    require('../src/modules/regions/region.service').validateRegion = async () => ({ ok: true, region: { state: 'Tamil Nadu', district: 'Chennai', block: '' } });
    require('../src/modules/members/paymentReconcile').paymentIsGone = async () => false;
    const notices = [];
    require('../src/modules/notifications/notification.service').dispatchInBackground = async (...args) => { notices.push(args); };
    const mails = [];
    let mailWorks = true;
    require('../src/core/utils/mailer').send = async value => { mails.push(value); return { sent: mailWorks }; };
    const axios = require('axios');
    let providerProfile = {};
    axios.post = async () => ({ data: { access_token: 'fixture-token' } });
    axios.get = async url => url.includes('/oauth/access_token') ? { data: { access_token: 'fixture-token' } }
        : url.endsWith('/me/permissions') ? { data: { data: [] } } : { data: providerProfile };
    const auth = require('../src/modules/auth/auth.service');
    const oauth = require('../src/modules/auth/oauth.service');
    const jwt = require('jsonwebtoken');
    const express = require('express'); const request = require('supertest');
    const app = express(); app.use(express.json()); app.use('/auth', require('../src/modules/auth/auth.routes'));
    app.use(require('../src/core/middleware/errorHandler').errorHandler);
    const profile = (subject, email, verified = true) => ({ id: subject, sub: subject, email, email_verified: verified, name: 'Fixture Person' });
    const start = async (provider, info, client = '') => {
        providerProfile = info;
        let nonce;
        const res = { cookie: (_name, value) => { nonce = value; }, clearCookie() {} };
        const target = new URL(oauth.startUrl(provider, { query: { client }, headers: {} }, res));
        const result = await oauth.handleCallback(provider, { query: { code: 'fixture-code', state: target.searchParams.get('state') }, headers: { cookie: `activ_oauth=${nonce}` } }, res);
        const parsed = new URL(result);
        const code = new URLSearchParams(client ? parsed.search.slice(1) : parsed.hash.slice(1)).get('code');
        assert(code, result); return code;
    };
    const member = await auth.register({ email: 'existing@gmail.com', password: 'local-password', fullName: 'Existing Member', phoneNumber: '9123456780', whatsappNumber: '9123456780', state: 'Tamil Nadu', district: 'Chennai' });
    assert(member.token); assert.equal(member.memberDetails.membershipStatus, 'pending'); assert.equal(member.memberDetails.profileCompleted, false);
    assert.equal(await Application.countDocuments(), 0, 'account creation does not submit an application');
    const existingId = String(member.user.id);
    let code = await start('google', profile('google-existing', 'existing@gmail.com'));
    let session = await oauth.exchange(code);
    assert.equal(String(session.user.id), existingId, 'forgotten password + verified Google opens the same account');
    assert.equal(session.user.role, 'member');
    await assert.rejects(oauth.exchange(code), /already been used/);
    code = await start('google', profile('google-existing', 'changed@gmail.com'), 'app');
    assert.equal(String((await oauth.exchange(code)).user.id), existingId, 'provider subject survives email change');
    assert.equal(await Member.countDocuments({ email: 'changed@gmail.com' }), 0);
    code = await start('google', profile('google-new', 'new@gmail.com'));
    const concurrent = await Promise.allSettled([oauth.exchange(code), oauth.exchange(code)]);
    assert.equal(concurrent.filter(row => row.status === 'fulfilled').length, 1);
    const created = concurrent.find(row => row.status === 'fulfilled').value;
    assert.equal(created.memberDetails.registrationIncomplete, true);
    assert.equal(created.memberDetails.membershipStatus, 'pending'); assert.equal(created.memberDetails.profileCompleted, false);
    assert.equal(created.memberDetails.membershipType, 'none'); assert.equal(created.user.role, 'member');
    assert.equal(await Member.countDocuments({ email: 'new@gmail.com' }), 1);
    assert(await Auth.exists({ email: 'new@gmail.com' }), 'social accounts have an actual credential record for profile completion');
    assert.equal(await Application.countDocuments(), 0);
    code = await start('google', { ...profile('google-no-name', 'noname@gmail.com'), name: '' });
    assert.equal((await oauth.exchange(code)).memberDetails.fullName, '', 'missing provider name remains an incomplete field, never a fake name');
    code = await start('facebook', profile('facebook-existing', 'existing@gmail.com'));
    const challenge = await oauth.exchange(code);
    assert.equal(challenge.requiresEmailVerification, true); assert.equal(challenge.token, undefined);
    assert.equal(await Identity.countDocuments({ provider: 'facebook' }), 0, 'unverified Facebook email never auto-links');
    await request(app).post('/auth/oauth/verify-email').send({ code, email: 'victim@example.test,attacker' }).expect(400);
    await request(app).post('/auth/oauth/verify-email').send({ code, email: 'existing@gmail.com' }).expect(200);
    assert.equal(mails.at(-1).privateRecipientOnly, true, 'verification is never archive-copied');
    const otp = mails.at(-1).text.match(/code is (\d{6})/)[1];
    const flow = await Flow.findById(jwt.verify(code, process.env.JWT_SECRET).jti).lean();
    assert(!JSON.stringify(flow).includes(otp), 'only HMAC code hash is stored');
    await request(app).post('/auth/oauth/verify-email').send({ code, email: 'existing@gmail.com' }).expect(429);
    await request(app).post('/auth/oauth/exchange').send({ code, verificationCode: '000000' }).expect(400);
    const verified = await request(app).post('/auth/oauth/exchange').send({ code, verificationCode: otp, role: 'super_admin', membershipStatus: 'active' }).expect(200);
    assert.equal(String(verified.body.data.user.id), existingId); assert.equal(verified.body.data.user.role, 'member');
    assert.equal(verified.body.data.memberDetails.membershipStatus, 'pending');
    await request(app).post('/auth/oauth/exchange').send({ code, verificationCode: otp }).expect(401);
    code = await start('facebook', profile('facebook-existing', undefined, undefined));
    assert.equal(String((await oauth.exchange(code)).user.id), existingId, 'linked Facebook works even when email is no longer shared');
    code = await start('linkedin', profile('linkedin-new', 'linkedin@example.test'));
    assert.equal((await oauth.exchange(code)).memberDetails.registrationIncomplete, true);
    for (const provider of ['google', 'linkedin']) {
        code = await start(provider, profile(`${provider}-unverified`, 'unverified@example.test', false));
        assert.equal((await oauth.exchange(code)).requiresEmailVerification, true);
        assert.equal(await Auth.exists({ email: 'unverified@example.test' }), null);
    }
    code = await start('google', profile('google-third-party', 'external@example.test', true));
    assert.equal((await oauth.exchange(code)).requiresEmailVerification, true, 'Google third-party email is independently verified');
    code = await start('facebook', profile('facebook-no-email', undefined));
    assert.equal((await oauth.exchange(code)).email, '', 'missing provider email can be entered and verified');
    await oauth.requestEmail(code, 'new-facebook@example.test');
    const fbOtp = mails.at(-1).text.match(/code is (\d{6})/)[1];
    assert.equal((await oauth.exchange(code, { verificationCode: fbOtp })).memberDetails.registrationIncomplete, true);
    code = await start('google', profile('admin-subject', 'admin@gmail.com'));
    await assert.rejects(oauth.exchange(code), /Administrators/);
    assert.equal(await Auth.exists({ email: 'admin@gmail.com' }), null);
    await Member.updateOne({ email: 'existing@gmail.com' }, { $set: { isActive: false } });
    code = await start('facebook', profile('facebook-existing', 'other@example.test'));
    await assert.rejects(oauth.exchange(code), /blocked/);
    await Member.updateOne({ email: 'existing@gmail.com' }, { $set: { isActive: true } });
    await Auth.updateOne({ email: 'existing@gmail.com' }, { $set: { isActive: false } });
    code = await start('google', profile('google-existing', 'existing@gmail.com'));
    await assert.rejects(oauth.exchange(code), /blocked/);
    code = await start('facebook', profile('tries-subject', 'attempts@example.test'));
    await oauth.requestEmail(code, 'attempts@example.test');
    const limitedOtp = mails.at(-1).text.match(/code is (\d{6})/)[1];
    for (let i = 0; i < 5; i++) await assert.rejects(oauth.exchange(code, { verificationCode: '000000' }), /incorrect or expired/);
    await assert.rejects(oauth.exchange(code, { verificationCode: limitedOtp }), /incorrect or expired/);
    code = await start('facebook', profile('mail-fail', 'mail-fail@example.test'));
    mailWorks = false;
    await assert.rejects(oauth.requestEmail(code, 'mail-fail@example.test'), /could not send/);
    assert.equal(await Auth.exists({ email: 'mail-fail@example.test' }), null);
    const expiredId = jwt.verify(code, process.env.JWT_SECRET).jti;
    await Flow.updateOne({ _id: expiredId }, { $set: { expiresAt: new Date(Date.now() - 1) } });
    await assert.rejects(oauth.exchange(code), /expired/);
    console.log('PASS OAuth onboarding: password account/dashboard, all providers, secure first-email association, stable subjects, draft accounts, same-member recovery, no approval bypass, hashed private verification, rate/attempt/expiry limits, blocked/admin refusal and concurrent single use.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await mongoose.disconnect(); if (mongo) await mongo.stop(); process.exit(process.exitCode || 0); });
